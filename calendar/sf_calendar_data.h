/* ==================================================================
 * sf_calendar_data.h —— 古历归日表（**自动生成，勿手改**）
 *
 * 由 experimental/gen_calendar_data.py 从 taiyin-ephemeris 的
 *     src/chinese_calendar/historical_calendar_data.h
 * 机械转换而来，数据一个字节未改。改数据请改上游再重跑脚本。
 *
 * ------------------------------------------------------------------
 * 表的构成
 *
 * 本表并非「重新实现每个朝代的历法」，而是**相对于均值模型的 ±1 天残差**：
 *   1. 分段线性拟合   exactSegments：每段给 (起始事件序号, 段长, 基准, 每事件步进)
 *                     —— 段边界正好是各代历法的**改历点**
 *                     （春秋 / 战国 / 秦汉 / 太初历 / 四分历 / 景初历 /
 *                       元嘉历 / 大明历 / 开皇历 / 大业历 …）
 *   2. 稀疏残差       residualMask 逐位标记「这一条线性预测不对」，
 *                     residualSigns 给 ±1 天，residualRank 是分块 popcount 前缀表
 *   3. 节气相位       phaseTicks[localIndex % 24] 的附加修正（含义上游未写，照搬）
 *
 * 覆盖：朔 前 722-12-17 … 1959-12-30（33161 条）
 *       气 前 221-11-09 … 1959-12-22（52324 条）
 *       注意：起点**不对称是有意为之**：前 722…前 221 之间是「朔用古历、气用天文」。
 *       1960-01-01 之后一律走天文计算（见 SF_HIST_PROFILE_END_JD）。
 *
 * ------------------------------------------------------------------
 * 来源与许可
 *
 * 数据出自**寿星万年历**（sxwnl，许剑伟）的历史历法归日表，经
 * taiyin-ephemeris 打包。上游不提供常规 SPDX 许可，其古历数据不主张
 * 按 MPL-2.0 重新许可 —— 详见 NOTICE。
 *
 * 日历日号是**东经 120° 的民用日**，不是 UT 里的天文时刻。
 *
 * ------------------------------------------------------------------
 * 搬表校验
 *
 * 仅靠「农历 fixture 通过」不够 —— 那只有 8 个点。真正的验证是下面两个
 * **oracle 哈希**：它们是对**整张归日表**（85485 条）逐日算的
 *
 *     sha256(concat(f"{day}\n" for day in days))
 *
 * 只要解码器有一位错，哈希就对不上。做法是把全部归日 dump 出来再哈希：
 *
 *     cc -std=c99 -I. -o /tmp/dumpdays test/dump_hist_days.c \
 *        sf_fixed.o sf_series.o sf_solve.o sf_calendar.o -lm
 *     /tmp/dumpdays | python3 -c '...'      # 见 experimental/verify_calendar_data.py
 *
 * 本库移植完成时两个哈希都已核对通过。
 * ================================================================== */
